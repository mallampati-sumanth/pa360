CREATE TABLE IF NOT EXISTS PA360_DEV.CURATED.AUTHORIZATION_REQUESTS (
    AUTHORIZATION_ID VARCHAR(36) PRIMARY KEY,
    PATIENT_ID VARCHAR(50) REFERENCES PA360_DEV.CURATED.PATIENTS(PATIENT_ID),
    PROVIDER_ID VARCHAR(50) REFERENCES PA360_DEV.CURATED.PROVIDERS(PROVIDER_ID),
    PAYER_ID VARCHAR(50) REFERENCES PA360_DEV.CURATED.PAYERS(PAYER_ID),
    PLAN_ID VARCHAR(50) REFERENCES PA360_DEV.CURATED.PLANS(PLAN_ID),
    SERVICE_CODE VARCHAR(20) REFERENCES PA360_DEV.CURATED.SERVICES(SERVICE_CODE),
    DIAGNOSIS VARCHAR(20),
    CLINICAL_INDICATION TEXT,
    REQUEST_DATE DATE DEFAULT CURRENT_DATE(),
    STATUS VARCHAR(50) NOT NULL DEFAULT 'Draft',
    PRIORITY VARCHAR(20) DEFAULT 'ROUTINE',
    MISSING_INFORMATION VARIANT,
    SUPPORTING_DOCUMENT VARCHAR(500),
    SUBMISSION_DATE DATE,
    DECISION_DATE DATE,
    NOTES TEXT,
    REVIEWED_BY_USER_ID VARCHAR(50),
    AI_CONFIDENCE_SCORE FLOAT,
    AI_SUMMARY TEXT,
    REQUIRES_HUMAN_REVIEW BOOLEAN DEFAULT FALSE,
    HUMAN_REVIEW_REASON TEXT,
    EDGE_CASE_TYPE VARCHAR(50) DEFAULT 'NONE',
    EDGE_CASE_NOTES TEXT,
    IS_RETRO_AUTH BOOLEAN DEFAULT FALSE,
    RETRO_AUTH_REASON TEXT,
    DENIAL_CODE VARCHAR(20),
    DENIAL_REASON TEXT,
    APPEAL_STATUS VARCHAR(50) DEFAULT 'NOT_APPLICABLE',
    PRIMARY_PAYER_ID VARCHAR(50),
    SECONDARY_PAYER_ID VARCHAR(50),
    COVERAGE_VERIFIED BOOLEAN DEFAULT FALSE,
    COVERAGE_NOTES TEXT,
    REUSED_FROM_AUTHORIZATION_ID VARCHAR(36),
    CLINICAL_CHANGE_DETECTED BOOLEAN DEFAULT FALSE,
    CLINICAL_CHANGE_NOTES TEXT,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    INGESTION_TIMESTAMP TIMESTAMP_NTZ,
    SOURCE_BATCH_ID VARCHAR(100),
    PROCESSING_STATUS VARCHAR(20) DEFAULT 'ACTIVE',
    PIPELINE_VERSION VARCHAR(20)
);
